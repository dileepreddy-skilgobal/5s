import { IsString, IsOptional, IsIn, IsArray, ArrayMaxSize, ValidateNested, IsNumber, Min, Max, IsDateString, MaxLength, Matches } from 'class-validator';
import { Type } from 'class-transformer';
import { values } from '../../../core/validation/domain-values';

/** One piece of supporting evidence (upload video / audio / documents via POST /files first). */
export class ObservationMediaDto {
  @IsString()
  @MaxLength(2000)
  url: string;

  @IsIn(['PHOTO', 'VIDEO', 'AUDIO', 'DOCUMENT'])
  kind: string;

  @IsOptional()
  @IsDateString()
  capturedAt?: string;

  @IsOptional() @IsNumber() @Min(-90) @Max(90) latitude?: number;
  @IsOptional() @IsNumber() @Min(-180) @Max(180) longitude?: number;
}

export class CreateObservationDto {
  @IsString()
  locationId: string;

  @IsString()
  @IsIn(values('FIVE_S_CATEGORIES'))
  category: string;

  @IsString()
  @IsIn(values('OBSERVATION_SEVERITIES'))
  severity: string;

  @IsString()
  title: string;

  @IsString()
  description: string;

  @IsOptional()
  @IsString()
  beforePhotoUrl?: string;

  @IsOptional()
  @IsString()
  annotatedPhotoUrl?: string;

  @IsOptional()
  annotationData?: any; // JSON or string

  @IsOptional()
  @IsString()
  riskAssessment?: string;

  /** Array of tag strings, or an already-serialised JSON string (the service accepts both). */
  @IsOptional()
  tags?: string[] | string;

  @IsOptional()
  @IsArray()
  @ArrayMaxSize(10)
  @ValidateNested({ each: true })
  @Type(() => ObservationMediaDto)
  mediaUrls?: ObservationMediaDto[];

  @IsOptional()
  @IsString()
  voiceNoteUrl?: string;

  @IsOptional() @IsNumber() @Min(-90) @Max(90) gpsLatitude?: number;
  @IsOptional() @IsNumber() @Min(-180) @Max(180) gpsLongitude?: number;
  @IsOptional() @IsNumber() @Min(0) @Max(100000) gpsAccuracyM?: number;

  /** Idempotency key generated by offline-capable clients (UUID); a retry returns the original observation. */
  @IsOptional()
  @Matches(/^[A-Za-z0-9-]{8,64}$/)
  clientRequestId?: string;
}

export class UpdateObservationDto {
  @IsOptional()
  @IsString()
  title?: string;

  @IsOptional()
  @IsString()
  description?: string;

  @IsOptional()
  @IsString()
  @IsIn(values('OBSERVATION_SEVERITIES'))
  severity?: string;

  @IsOptional()
  @IsString()
  @IsIn(values('FIVE_S_CATEGORIES'))
  category?: string;

  @IsOptional()
  @IsString()
  @IsIn(values('OBSERVATION_STATUSES'))
  status?: string;

  @IsOptional()
  @IsString()
  riskAssessment?: string;

  /** Array of tag strings, or an already-serialised JSON string (the service accepts both). */
  @IsOptional()
  tags?: string[] | string;
}
