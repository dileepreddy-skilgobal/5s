import * as XLSX from 'xlsx';
import PDFDocument = require('pdfkit');
import { ReportColumn, ReportRow } from './report-registers';

export interface ReportMeta {
  title: string;
  organization: string;
  generatedBy: string;
  generatedAt: Date;
  /** Human-readable applied filters, e.g. ["Status: OPEN", "From: 2026-01-01"]. */
  filters: string[];
  /** Headline figures over every matching record (e.g. action ageing buckets), shown above the table. */
  summary?: string[];
}

const iso = (d: Date) => d.toISOString().slice(0, 10);
const isoTime = (d: Date) => d.toISOString().replace('T', ' ').slice(0, 16);

/** Display text for a cell (CSV / PDF). */
export function formatCell(value: ReportRow[string], type: ReportColumn['type']): string {
  if (value === null || value === undefined) return '';
  if (value instanceof Date) return type === 'datetime' ? isoTime(value) : iso(value);
  if (typeof value === 'boolean') return value ? 'Yes' : 'No';
  if (typeof value === 'number') return type === 'percent' ? value.toFixed(1) : String(Math.round(value * 100) / 100);
  return String(value);
}

/**
 * Cells starting with = + - @ (or tab / CR) are executed as formulas by spreadsheet apps;
 * prefixing an apostrophe neutralises CSV/formula injection.
 */
const guardFormula = (s: string) => (/^[=+\-@\t\r]/.test(s) ? `'${s}` : s);

export function toCsv(columns: ReportColumn[], rows: ReportRow[]): Buffer {
  const escape = (s: string) => (/[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
  const lines = [
    columns.map((c) => escape(c.label)).join(','),
    ...rows.map((r) => columns.map((c) => escape(guardFormula(formatCell(r[c.key], c.type)))).join(',')),
  ];
  // UTF-8 BOM so Excel opens accented names correctly
  return Buffer.from('﻿' + lines.join('\r\n'), 'utf8');
}

export function toXlsx(meta: ReportMeta, columns: ReportColumn[], rows: ReportRow[]): Buffer {
  const header = columns.map((c) => c.label);
  const body = rows.map((r) =>
    columns.map((c) => {
      const v = r[c.key];
      if (v === null || v === undefined) return null;
      if (typeof v === 'string') return guardFormula(v);
      if (typeof v === 'boolean') return v ? 'Yes' : 'No';
      return v; // numbers and dates keep their type so Excel can sort / filter
    }),
  );
  const sheet = XLSX.utils.aoa_to_sheet([header, ...body], { cellDates: true });
  sheet['!cols'] = columns.map((c) => ({ wch: Math.max(c.label.length + 2, Math.round(c.width * 14)) }));
  sheet['!autofilter'] = { ref: XLSX.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: Math.max(rows.length, 1), c: columns.length - 1 } }) };
  const info = XLSX.utils.aoa_to_sheet([
    ['Report', meta.title],
    ['Organization', meta.organization],
    ['Generated', isoTime(meta.generatedAt) + ' UTC'],
    ['Generated by', meta.generatedBy],
    ['Rows', rows.length],
    ['Filters', meta.filters.length ? meta.filters.join('; ') : 'None'],
    ...(meta.summary?.length ? [['Summary', meta.summary.join('; ')]] : []),
  ]);
  info['!cols'] = [{ wch: 16 }, { wch: 60 }];
  const book = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(book, sheet, meta.title.slice(0, 31));
  XLSX.utils.book_append_sheet(book, info, 'Report info');
  return XLSX.write(book, { type: 'buffer', bookType: 'xlsx' }) as Buffer;
}

export function toPdf(meta: ReportMeta, columns: ReportColumn[], rows: ReportRow[]): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 30, bufferPages: true, info: { Title: meta.title, Author: meta.organization } });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const left = doc.page.margins.left;
    const usable = doc.page.width - left - doc.page.margins.right;
    const totalWeight = columns.reduce((s, c) => s + c.width, 0);
    const widths = columns.map((c) => (c.width / totalWeight) * usable);
    const fontSize = columns.length > 12 ? 6.5 : 7.5;
    const padding = 3.5;
    const headerHeight = fontSize * 2 + 2 * padding + 2;
    const maxCellHeight = fontSize * 3.6; // at most three lines per cell
    const bottom = () => doc.page.height - doc.page.margins.bottom - 14;

    const headerBlock = () => {
      doc.font('Helvetica-Bold').fontSize(14).fillColor('#111827').text(meta.title, left, doc.page.margins.top);
      doc.font('Helvetica').fontSize(8).fillColor('#4B5563')
        .text(`${meta.organization}  •  Generated ${isoTime(meta.generatedAt)} UTC by ${meta.generatedBy}  •  ${rows.length} row(s)`);
      if (meta.filters.length) doc.text(`Filters: ${meta.filters.join('; ')}`);
      if (meta.summary?.length) doc.text(`Summary: ${meta.summary.join('; ')}`);
      doc.moveDown(0.6);
    };
    const tableHeader = () => {
      const y = doc.y;
      doc.rect(left, y, usable, headerHeight).fill('#1F2937');
      let x = left;
      doc.font('Helvetica-Bold').fontSize(fontSize).fillColor('#FFFFFF');
      columns.forEach((c, i) => {
        doc.text(c.label, x + 2, y + padding, { width: widths[i] - 4, height: headerHeight - padding, ellipsis: true });
        x += widths[i];
      });
      doc.y = y + headerHeight;
    };

    headerBlock();
    tableHeader();
    doc.font('Helvetica').fontSize(fontSize);
    rows.forEach((r, idx) => {
      // Status codes read better as words in print (CSV / Excel keep the raw codes for filtering)
      const cells = columns.map((c) => formatCell(r[c.key], c.type)).map((t) => (/^[A-Z0-9]+(_[A-Z0-9]+)+$/.test(t) ? t.replace(/_/g, ' ') : t));
      // Long values wrap (up to three lines) instead of being cut off
      const contentHeight = Math.min(
        maxCellHeight,
        Math.max(fontSize, ...cells.map((text, i) => (text ? doc.heightOfString(text, { width: widths[i] - 4 }) : 0))),
      );
      const rowHeight = contentHeight + 2 * padding;
      if (doc.y + rowHeight > bottom()) {
        doc.addPage();
        doc.y = doc.page.margins.top;
        tableHeader();
        doc.font('Helvetica').fontSize(fontSize);
      }
      const y = doc.y;
      if (idx % 2 === 1) doc.rect(left, y, usable, rowHeight).fill('#F3F4F6');
      doc.fillColor('#111827');
      let x = left;
      cells.forEach((text, i) => {
        doc.text(text, x + 2, y + padding, { width: widths[i] - 4, height: contentHeight + 1, ellipsis: true });
        x += widths[i];
      });
      doc.y = y + rowHeight;
    });
    if (rows.length === 0) doc.font('Helvetica-Oblique').fontSize(9).fillColor('#6B7280').text('No records match the selected filters.', left, doc.y + 6);

    // Page numbers
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      // Writing inside the bottom margin would otherwise make PDFKit start a new page
      const margin = doc.page.margins.bottom;
      doc.page.margins.bottom = 0;
      doc.font('Helvetica').fontSize(7).fillColor('#6B7280')
        .text(`Page ${i + 1} of ${range.count}`, left, doc.page.height - margin - 8, { width: usable, align: 'right', lineBreak: false });
      doc.page.margins.bottom = margin;
    }
    doc.end();
  });
}
