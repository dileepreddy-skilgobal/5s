import React, { useCallback, useEffect, useState } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import { useApp } from '../../context/AppContext';
import { useTerminology } from '../../hooks/useTerminology';
import { useDebouncedValue } from '../../hooks/useDebouncedValue';
import { api, getApiErrorMessage } from '../../services/api';
import { masterDataApi, QrBatchItem } from '../../services/masterDataApi';
import { areasApi } from '../../services/api-areas';
import { Location, OrgNode, User } from '../../types';
import { Card } from '../../components/ui/Card';
import { PageHeader } from '../../components/ui/PageHeader';
import { SummaryCard, SummaryGrid } from '../../components/ui/SummaryCard';
import { FilterBar, SearchInput } from '../../components/ui/FormField';
import { QrCodeImage } from '../../components/common/QrCodeImage';
import { Button } from '../../components/ui/Button';
import { Badge } from '../../components/ui/Badge';
import { Modal } from '../../components/ui/Modal';
import { EmptyState, ErrorState, LoadingState } from '../../components/ui/StateViews';
import {
  FREQUENCY_LABELS,
  LOCATION_STATUS_LABELS,
  LOCATION_TYPE_LABELS,
  RISK_LABELS,
  frequencyLabel,
  locationStatusLabel,
  locationTypeLabel,
  riskLabel,
  riskVariant,
} from '../../constants/labels';
import { LocationFormModal, LOCATION_FREQUENCIES } from './LocationFormModal';
import { MapPin, Plus, QrCode, ShieldAlert, Calendar, Printer, UserX } from 'lucide-react';

/** Roles that look after specific areas and start on "My areas". */
const AREA_ROLES = ['AREA_OWNER', 'DEPT_HEAD'];

const statusVariant = (status: string) => (status === 'ACTIVE' ? 'success' : status === 'UNDER_MAINTENANCE' ? 'warning' : 'neutral');

export const LocationsPage: React.FC = () => {
  const navigate = useNavigate();
  const { currentTenant, currentUser, activeUserRole, addToast, can } = useApp();
  const { relabel } = useTerminology();
  const [locations, setLocations] = useState<Location[]>([]);
  const [orgNodes, setOrgNodes] = useState<OrgNode[]>([]);
  const [users, setUsers] = useState<User[]>([]);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState<string | null>(null);

  // Filters
  const [search, setSearch] = useState('');
  // Query the API only after typing pauses, not on every keystroke
  const debouncedSearch = useDebouncedValue(search);
  const [selectedNodeId, setSelectedNodeId] = useState('');
  const [selectedType, setSelectedType] = useState('');
  const [selectedRisk, setSelectedRisk] = useState('');
  const [selectedFreq, setSelectedFreq] = useState('');
  const [selectedStatus, setSelectedStatus] = useState('');
  const [selectedOwner, setSelectedOwner] = useState('');
  // Area owners and department heads see their own areas first: owned / backed up, or under the units their role covers
  const showMine = !!currentUser?.roles.some((r) => AREA_ROLES.includes(r.code));
  const [mineOnly, setMineOnly] = useState(() => AREA_ROLES.includes(activeUserRole));

  const [createOpen, setCreateOpen] = useState(false);
  const [qrLocation, setQrLocation] = useState<Location | null>(null);
  const [qrItem, setQrItem] = useState<QrBatchItem | null>(null);
  const [qrError, setQrError] = useState<string | null>(null);

  const loadData = useCallback(async () => {
    if (!currentTenant) return;
    setLoading(true);
    setLoadError(null);
    try {
      const [locsData, nodesData, usersData] = await Promise.all([
        areasApi.getLocations({
          search: debouncedSearch || undefined,
          orgNodeId: selectedNodeId || undefined,
          locationType: selectedType || undefined,
          riskLevel: selectedRisk || undefined,
          auditFrequency: selectedFreq || undefined,
          status: selectedStatus || undefined,
          ownerId: selectedOwner || undefined,
          mine: showMine && mineOnly,
        }),
        api.getOrgNodes(),
        api.getUsers(),
      ]);
      setLocations(locsData);
      setOrgNodes(nodesData);
      setUsers(usersData);
    } catch (err) {
      setLoadError(getApiErrorMessage(err, 'The locations could not be loaded.'));
    } finally {
      setLoading(false);
    }
  }, [currentTenant, debouncedSearch, selectedNodeId, selectedType, selectedRisk, selectedFreq, selectedStatus, selectedOwner, showMine, mineOnly]);

  useEffect(() => {
    loadData();
  }, [loadData]);

  // The tag is generated by the server so it shows exactly what is encoded (and repairs old payloads)
  const openQr = async (loc: Location) => {
    setQrLocation(loc);
    setQrItem(null);
    setQrError(null);
    try {
      const [item] = await masterDataApi.getBatchQrCodes([loc.id]);
      if (!item) setQrError('The QR tag could not be loaded.');
      else setQrItem(item);
    } catch (err) {
      setQrError(getApiErrorMessage(err, 'The QR tag could not be loaded.'));
    }
  };

  const filtersActive = !!(search || selectedNodeId || selectedType || selectedRisk || selectedFreq || selectedStatus || selectedOwner || (showMine && mineOnly));
  const clearFilters = () => {
    setSearch('');
    setSelectedOwner('');
    setMineOnly(false);
    setSelectedNodeId('');
    setSelectedType('');
    setSelectedRisk('');
    setSelectedFreq('');
    setSelectedStatus('');
  };

  const activeCount = locations.filter((l) => l.status === 'ACTIVE').length;
  const highRiskCount = locations.filter((l) => l.riskLevel === 'HIGH' || l.riskLevel === 'CRITICAL').length;
  const weeklyCount = locations.filter((l) => l.auditFrequency === 'WEEKLY').length;
  const unownedCount = locations.filter((l) => !l.ownerId).length;

  return (
    <div className="animate-fade-in" style={{ display: 'flex', flexDirection: 'column', gap: '24px' }}>
      <PageHeader
        title={relabel('Locations')}
        description={relabel('Every audited area, with its owner, QR tag and 5S roll-out plan.')}
        actions={
          can('LOCATION_EDITORS') ? (
            <Button variant="primary" icon={<Plus size={16} />} onClick={() => setCreateOpen(true)}>
              {relabel('New location')}
            </Button>
          ) : undefined
        }
      />

      <SummaryGrid>
        <SummaryCard icon={<MapPin size={18} />} tone="primary" label={filtersActive ? 'Active (filtered)' : 'Active'} value={activeCount} />
        <SummaryCard icon={<ShieldAlert size={18} />} tone="danger" label="High / critical risk" value={highRiskCount} />
        <SummaryCard icon={<Calendar size={18} />} tone="info" label="Audited weekly" value={weeklyCount} />
        <SummaryCard icon={<UserX size={18} />} tone="warning" label="Without an owner" value={unownedCount} />
      </SummaryGrid>

      <FilterBar label="Filter locations">
        <SearchInput
          label="Search locations"
          placeholder="Search by area code, name or building"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
        />
        <select className="form-select" aria-label="Organization unit" value={selectedNodeId} onChange={(e) => setSelectedNodeId(e.target.value)}>
          <option value="">All units</option>
          {orgNodes.map((n) => (
            <option key={n.id} value={n.id}>{n.name} ({n.code})</option>
          ))}
        </select>
        <select className="form-select" aria-label="Type" value={selectedType} onChange={(e) => setSelectedType(e.target.value)}>
          <option value="">All types</option>
          {Object.entries(LOCATION_TYPE_LABELS).map(([code, label]) => <option key={code} value={code}>{label}</option>)}
        </select>
        <select className="form-select" aria-label="Risk level" value={selectedRisk} onChange={(e) => setSelectedRisk(e.target.value)}>
          <option value="">All risk levels</option>
          {Object.entries(RISK_LABELS).map(([code, label]) => <option key={code} value={code}>{label}</option>)}
        </select>
        <select className="form-select" aria-label="Audit frequency" value={selectedFreq} onChange={(e) => setSelectedFreq(e.target.value)}>
          <option value="">All frequencies</option>
          {LOCATION_FREQUENCIES.map((code) => <option key={code} value={code}>{FREQUENCY_LABELS[code]}</option>)}
        </select>
        <select className="form-select" aria-label="Status" value={selectedStatus} onChange={(e) => setSelectedStatus(e.target.value)}>
          <option value="">All statuses</option>
          {Object.entries(LOCATION_STATUS_LABELS).map(([code, label]) => <option key={code} value={code}>{label}</option>)}
        </select>
        <select className="form-select" aria-label="Owner" value={selectedOwner} onChange={(e) => setSelectedOwner(e.target.value)}>
          <option value="">All owners</option>
          {users
            .filter((u) => u.status === 'ACTIVE')
            .map((u) => <option key={u.id} value={u.id}>{`${u.firstName} ${u.lastName}`.trim() || u.email}</option>)}
        </select>
        {showMine && (
          <button
            type="button"
            className={`pillar-tab-pill${mineOnly ? ' active' : ''}`}
            aria-pressed={mineOnly}
            title="Areas you own or back up, and those under the units your role covers"
            onClick={() => setMineOnly((v) => !v)}
            style={{ flex: '0 0 auto', whiteSpace: 'nowrap' }}
          >
            My areas
          </button>
        )}
        {filtersActive && (
          <Button variant="ghost" onClick={clearFilters} style={{ flex: '0 0 auto' }}>Clear filters</Button>
        )}
      </FilterBar>

      <Card noPadding>
        {loading && locations.length === 0 ? (
          <LoadingState label="Loading locations…" />
        ) : loadError ? (
          <ErrorState message={loadError} onRetry={loadData} />
        ) : locations.length === 0 ? (
          <EmptyState
            icon={<MapPin size={28} />}
            title={filtersActive ? (mineOnly && showMine ? 'No areas are assigned to you here' : 'No locations match these filters') : 'No locations yet'}
            description={filtersActive ? 'Change or clear the filters.' : can('LOCATION_EDITORS') ? 'Create the first location, or import them from a spreadsheet.' : undefined}
            action={filtersActive ? <Button size="sm" variant="secondary" onClick={clearFilters}>Clear filters</Button> : undefined}
          />
        ) : (
          <div className="enterprise-table-container" aria-busy={loading}>
            <table className="enterprise-table">
              <thead>
                <tr>
                  <th>Area code</th>
                  <th>Location</th>
                  <th>Unit</th>
                  <th>Type</th>
                  <th>Risk</th>
                  <th>Audit frequency</th>
                  <th>Status</th>
                  <th>Owner</th>
                  <th style={{ textAlign: 'right' }}><span className="sr-only">QR tag</span></th>
                </tr>
              </thead>
              <tbody>
                {locations.map((loc) => {
                  const place = [loc.building, loc.floor].filter(Boolean).join(' • ');
                  return (
                    <tr key={loc.id}>
                      <td style={{ whiteSpace: 'nowrap' }}>
                        <span className="code-tag" style={{ whiteSpace: 'nowrap' }}>
                          {loc.areaCode}
                        </span>
                      </td>
                      <td style={{ minWidth: '180px' }}>
                        <Link to={`/locations/${loc.id}`} style={{ fontWeight: 600, color: 'var(--color-primary)' }}>{loc.name}</Link>
                        {place && <div style={{ fontSize: '12.5px', color: 'var(--text-secondary)', marginTop: '2px' }}>{place}</div>}
                      </td>
                      <td style={{ minWidth: '160px' }}>
                        {loc.orgNode ? (
                          <>
                            <div style={{ color: 'var(--text-primary)' }}>{loc.orgNode.name}</div>
                            <div style={{ fontSize: '12px', color: 'var(--text-tertiary)', whiteSpace: 'nowrap' }}>{loc.orgNode.code}</div>
                          </>
                        ) : (
                          '—'
                        )}
                      </td>
                      <td><Badge variant={loc.locationType === 'RED_TAG_ZONE' ? 'danger' : 'neutral'}>{locationTypeLabel(loc.locationType)}</Badge></td>
                      <td><Badge variant={riskVariant(loc.riskLevel)}>{riskLabel(loc.riskLevel)}</Badge></td>
                      <td style={{ color: 'var(--text-secondary)', whiteSpace: 'nowrap' }}>{frequencyLabel(loc.auditFrequency)}</td>
                      <td><Badge variant={statusVariant(loc.status)}>{locationStatusLabel(loc.status)}</Badge></td>
                      <td style={{ whiteSpace: 'nowrap' }}>
                        {loc.owner ? `${loc.owner.firstName} ${loc.owner.lastName}` : <span style={{ color: 'var(--text-tertiary)' }}>Unassigned</span>}
                      </td>
                      <td style={{ textAlign: 'right' }}>
                        <Button size="sm" variant="ghost" aria-label={`QR tag for ${loc.name}`} title="QR tag" onClick={() => openQr(loc)}>
                          <QrCode size={16} />
                        </Button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </Card>

      <LocationFormModal
        isOpen={createOpen}
        onClose={() => setCreateOpen(false)}
        orgNodes={orgNodes}
        users={users}
        onSaved={(newLoc) => {
          setCreateOpen(false);
          addToast({ type: 'success', title: 'Location created', message: `${newLoc.name} (${newLoc.areaCode}) was created with its QR tag and 5S milestones.` });
          navigate(`/locations/${newLoc.id}`);
        }}
      />

      <Modal
        isOpen={!!qrLocation}
        onClose={() => setQrLocation(null)}
        title={qrLocation ? `QR tag: ${qrLocation.areaCode}` : 'QR tag'}
        subtitle={qrLocation?.name}
        maxWidth="440px"
        footer={
          <>
            <Button variant="secondary" onClick={() => setQrLocation(null)}>Close</Button>
            <Button variant="primary" icon={<Printer size={16} />} onClick={() => window.print()} disabled={!qrItem?.qrDataUrl}>
              Print tag
            </Button>
          </>
        }
      >
        {qrLocation && (
          <div style={{ textAlign: 'center', padding: '16px' }}>
            {qrError ? (
              <ErrorState message={qrError} onRetry={() => openQr(qrLocation)} />
            ) : !qrItem ? (
              <LoadingState compact label="Generating QR tag…" />
            ) : (
              <>
                <div className="printable-station-tag" style={{ border: '2px dashed #CBD5E1', borderRadius: 'var(--radius-lg)', padding: '24px', display: 'inline-block', background: '#FFFFFF', maxWidth: '100%' }}>
                  {currentTenant?.name && (
                    <div style={{ fontSize: '12px', fontWeight: 700, color: '#003B70', marginBottom: '4px' }}>{currentTenant.name}</div>
                  )}
                  <div style={{ fontSize: '15px', fontWeight: 700, color: '#1D2733', marginBottom: '12px', whiteSpace: 'nowrap' }}>{qrItem.areaCode}</div>
                  <QrCodeImage
                    dataUrl={qrItem.qrDataUrl}
                    value={qrItem.qrPayload}
                    size={220}
                    alt={`QR code for ${qrItem.name}`}
                    style={{ width: '200px', height: '200px', margin: '0 auto', display: 'block' }}
                  />
                  <div style={{ fontSize: '13px', fontWeight: 600, color: '#1D2733', marginTop: '12px' }}>{qrItem.name}</div>
                  {[qrItem.building, qrItem.floor].filter(Boolean).length > 0 && (
                    <div style={{ fontSize: '11px', color: '#64748B', marginTop: '2px' }}>{[qrItem.building, qrItem.floor].filter(Boolean).join(' • ')}</div>
                  )}
                </div>
                <div style={{ fontSize: '11px', color: 'var(--text-tertiary)', marginTop: '16px', overflowWrap: 'anywhere' }}>
                  Payload: <code>{qrItem.qrPayload}</code>
                </div>
              </>
            )}
          </div>
        )}
      </Modal>
    </div>
  );
};
